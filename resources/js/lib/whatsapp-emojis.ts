export function allWhatsappEmojis(): string[] {
    const seen = new Set<string>();
    const out: string[] = [];
    for (const category of WHATSAPP_EMOJI_CATEGORIES) {
        for (const emoji of category.emojis) {
            if (seen.has(emoji)) {
                continue;
            }
            seen.add(emoji);
            out.push(emoji);
        }
    }
    return out;
}
