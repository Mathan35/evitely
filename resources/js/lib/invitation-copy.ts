export function copyFor(locale: string): InvitationCopy {
    const base = invitationCopy[locale] ?? english;

    return { ...english, ...base, ...(galleryChrome[locale] ?? {}) };
}

/** Remap static gallery nav labels for the active locale. */
export function localizedSiteNav(
    locale: string,
    items: { id: string; label: string }[],
): { id: string; label: string }[] {
    const copy = copyFor(locale);
    const labels: Record<string, string> = {
        home: copy.navHome,
        card: copy.navCard,
        story: copy.navStory,
        gallery: copy.navGallery,
        itinerary: copy.navItinerary,
        venue: copy.navVenue,
        guests: copy.navGuests,
        rsvp: copy.navRsvp,
    };

    return items.map((item) => ({
        ...item,
        label: labels[item.id] ?? item.label,
    }));
}
