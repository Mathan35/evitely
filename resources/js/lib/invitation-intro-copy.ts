export function introCopyFor(eventSlug?: string | null, locale?: string | null): IntroEventCopy {
    const event = normalizeIntroEventSlug(eventSlug);
    const lang = (locale || 'en').trim().toLowerCase() || 'en';
    const base = EVENT_COPY_EN[event] ?? EVENT_COPY_EN.custom;
    const localeBucket = LOCALE_EVENT[lang];
    if (!localeBucket) {
        return { ...base };
    }
    const overlay = localeBucket[event] ?? localeBucket.custom ?? {};
    return { ...base, ...overlay };
}
