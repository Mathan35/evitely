export type WeddingGalleryPhoto = {
    src: string;
    title: string;
    note: string;
    span: 'hero' | 'tall' | 'wide' | 'square';
};

export function weddingGalleryPhotos(styleKey: string): WeddingGalleryPhoto[] {
    const start = Math.max(0, WEDDING_STYLE_KEYS.indexOf(styleKey as (typeof WEDDING_STYLE_KEYS)[number]));
    const spans: WeddingGalleryPhoto['span'][] = ['hero', 'tall', 'square', 'square', 'wide', 'tall', 'square', 'wide'];

    return GALLERY_MOMENTS.map((moment, index) => {
        const key = WEDDING_STYLE_KEYS[(start + index) % WEDDING_STYLE_KEYS.length];
        const portrait = spans[index] === 'tall';

        return {
            src: weddingHeroSrc(key, portrait ? 'mobile' : 'desktop'),
            title: moment.title,
            note: moment.note,
            span: spans[index],
        };
    });
}

