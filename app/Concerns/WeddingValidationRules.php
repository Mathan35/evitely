    protected function prepareWeddingBooleans(): void
    {
        if ($this->exists('music_enabled')) {
            $this->merge(['music_enabled' => $this->boolean('music_enabled')]);
        }

        if (is_array($this->input('sections'))) {
            $sections = [];

            foreach (config('wedding.sections') as $section) {
                if (array_key_exists($section, $this->input('sections'))) {
                    $sections[$section] = filter_var($this->input('sections')[$section], FILTER_VALIDATE_BOOLEAN);
                }
            }

            $this->merge(['sections' => $sections]);
        }
    }
